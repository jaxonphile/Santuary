CREATE TABLE pengguna (
	id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	nama_samaran VARCHAR2(50) NOT NULL,
	email VARCHAR2(120) NOT NULL UNIQUE,
	password_hash VARCHAR2(100) NOT NULL,
	peran VARCHAR2(20) DEFAULT 'PENGGUNA' NOT NULL
		CHECK (peran IN ('PENGGUNA', 'MODERATOR', 'ADMIN')),
	dibuat_pada TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL 
);

CREATE TABLE kategori_bullying (
	id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	nama_kategori VARCHAR2(80) NOT NULL UNIQUE,
	deskripsi VARCHAR2(255)
);

CREATE TABLE lembaga (
	id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	nama_lembaga VARCHAR2(120) NOT NULL,
	jenis VARCHAR2(60),
	wilayah VARCHAR2(80),
	kontak VARCHAR2(120),
	aktif NUMBER(1) DEFAULT 1 NOT NULL CHECK (aktif IN (0,1))
);

CREATE TABLE cerita (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  pengguna_id NUMBER NOT NULL REFERENCES pengguna(id),
  kategori_id NUMBER NOT NULL REFERENCES kategori_bullying(id),
  judul VARCHAR2(200) NOT NULL,
  isi CLOB NOT NULL,
  tingkat_keterlibatan VARCHAR2(20) NOT NULL
    CHECK (tingkat_keterlibatan IN ('BERCERITA','DUKUNGAN','LAPORAN')),
  label_sensitif NUMBER(1) DEFAULT 0 NOT NULL CHECK (label_sensitif IN (0,1)),
  status_moderasi VARCHAR2(20) DEFAULT 'MENUNGGU' NOT NULL
    CHECK (status_moderasi IN ('MENUNGGU','DISETUJUI','DISEMBUNYIKAN','DIHAPUS')),
  dibuat_pada TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE komentar (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  cerita_id NUMBER NOT NULL REFERENCES cerita(id),
  pengguna_id NUMBER NOT NULL REFERENCES pengguna(id),
  isi VARCHAR2(1000) NOT NULL,
  dibuat_pada TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE laporan_konten (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  pelapor_id NUMBER NOT NULL REFERENCES pengguna(id),
  cerita_id NUMBER REFERENCES cerita(id),
  komentar_id NUMBER REFERENCES komentar(id),
  alasan VARCHAR2(255) NOT NULL,
  dibuat_pada TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK (cerita_id IS NOT NULL OR komentar_id IS NOT NULL)
);

CREATE TABLE persetujuan (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  cerita_id NUMBER NOT NULL REFERENCES cerita(id),
  jenis_persetujuan VARCHAR2(40) NOT NULL,
  disetujui_pada TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE rujukan (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  cerita_id NUMBER NOT NULL REFERENCES cerita(id),
  lembaga_id NUMBER NOT NULL REFERENCES lembaga(id),
  status VARCHAR2(20) DEFAULT 'DITERIMA' NOT NULL
    CHECK (status IN ('DITERIMA','DIPROSES','SELESAI')),
  dirujuk_pada TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE log_status (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  rujukan_id NUMBER NOT NULL REFERENCES rujukan(id),
  status_lama VARCHAR2(20),
  status_baru VARCHAR2(20) NOT NULL,
  diubah_pada TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE log_moderasi (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  cerita_id NUMBER NOT NULL REFERENCES cerita(id),
  moderator_id NUMBER NOT NULL REFERENCES pengguna(id),
  aksi VARCHAR2(20) NOT NULL,
  alasan VARCHAR2(255),
  dicatat_pada TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);


SELECT table_name FROM user_tables WHERE table_name IN ('PENGGUNA','KATEGORI_BULLYING','LEMBAGA','CERITA','KOMENTAR','LAPORAN_KONTEN','PERSETUJUAN','RUJUKAN','LOG_STATUS','LOG_MODERASI') ORDER BY table_name
